ALTER TABLE products ADD COLUMN target_currency text NOT NULL DEFAULT 'EUR';
ALTER TABLE products ADD COLUMN target_drop_pct double precision;

CREATE TABLE price_alerts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id bigint NOT NULL REFERENCES products(id) ON DELETE CASCADE,
  page_id bigint REFERENCES pages(id) ON DELETE CASCADE,
  kind text NOT NULL CHECK (kind IN ('target', 'drop')),
  price double precision NOT NULL,
  currency text,
  price_converted double precision NOT NULL,
  comparison_currency text NOT NULL,
  baseline_price double precision,
  baseline_currency text,
  baseline_converted double precision,
  threshold double precision NOT NULL,
  threshold_currency text,
  created_at timestamptz NOT NULL DEFAULT now(),
  read_at timestamptz
);
CREATE INDEX idx_alerts_product ON price_alerts(product_id, created_at DESC);
ALTER TABLE price_alerts ENABLE row level security;

-- Recreate reset_sequences() to include price_alerts
CREATE OR REPLACE FUNCTION reset_sequences() RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  PERFORM setval(pg_get_serial_sequence('products', 'id'), COALESCE((SELECT max(id) FROM products), 0) + 1, false);
  PERFORM setval(pg_get_serial_sequence('pages', 'id'), COALESCE((SELECT max(id) FROM pages), 0) + 1, false);
  PERFORM setval(pg_get_serial_sequence('price_checks', 'id'), COALESCE((SELECT max(id) FROM price_checks), 0) + 1, false);
  PERFORM setval(pg_get_serial_sequence('price_alerts', 'id'), COALESCE((SELECT max(id) FROM price_alerts), 0) + 1, false);
END;
$$;