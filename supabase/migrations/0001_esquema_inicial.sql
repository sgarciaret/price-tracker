create table products (
  id bigint generated by default as identity primary key,
  name text not null,
  image_url text,
  created_at timestamptz not null default now()
);

create table pages (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  url text not null,
  store text not null,
  css_selector text,
  created_at timestamptz not null default now()
);
create index idx_pages_product on pages(product_id);

create table price_checks (
  id bigint generated by default as identity primary key,
  page_id bigint not null references pages(id) on delete cascade,
  price double precision,
  currency text,
  status text not null check (status in ('ok','not_found','blocked','error')),
  error_msg text,
  method text,
  checked_at timestamptz not null default now()
);
create index idx_checks_page on price_checks(page_id, checked_at desc);

alter table products enable row level security;   -- sin políticas: solo service_role
alter table pages enable row level security;
alter table price_checks enable row level security;

create function reset_sequences() returns void language sql as $$
  select setval(pg_get_serial_sequence('products','id'), coalesce((select max(id) from products), 1));
  select setval(pg_get_serial_sequence('pages','id'), coalesce((select max(id) from pages), 1));
  select setval(pg_get_serial_sequence('price_checks','id'), coalesce((select max(id) from price_checks), 1));
$$;
